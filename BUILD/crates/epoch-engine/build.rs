//! What ships with Epoch, read off the folder the installer bundles.
//!
//! One consumer: `relocate`, which moves a World somebody made out of the program folder and into
//! the vault. To do that it has to tell a World the installer laid down from one a person created
//! at runtime, and the only honest source for the first list is the folder the installer bundles
//! — `tauri.conf.json` maps `../../packs/<id>` to `packs/<id>` beside the binary.
//!
//! **Derived, never typed.** `erase::SHIPPED` was a typed id. It named `default` for two days
//! after `default` stopped shipping, so the guard protected a World that did not exist while the
//! one that did ship went unprotected. A list read off the directory cannot go stale that way:
//! add a pack and it is in the list, remove one and it is gone.

use std::path::PathBuf;

fn main() {
    let packs = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets it"))
        .join("../../packs");
    println!("cargo:rerun-if-changed={}", packs.display());

    let mut shipped: Vec<String> = std::fs::read_dir(&packs)
        .map(|entries| {
            entries
                .flatten()
                .filter(|entry| entry.path().join("pack.toml").is_file())
                .filter_map(|entry| entry.file_name().to_str().map(str::to_owned))
                .collect()
        })
        .unwrap_or_default();
    shipped.sort();

    let out =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets it")).join("shipped_worlds.rs");
    let body = format!(
        "/// The Worlds this build's installer lays down beside the binary. Generated by `build.rs`\n\
         /// from the folder it bundles, so it cannot name a World that no longer ships.\n\
         pub const SHIPPED: &[&str] = &{shipped:?};\n"
    );
    std::fs::write(out, body).expect("the list of shipped Worlds could be written");
}
