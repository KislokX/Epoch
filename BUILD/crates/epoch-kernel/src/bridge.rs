//! What a Host and a remote machine say to each other (ADR-0029).
//!
//! ## Why this is in the Kernel
//!
//! Two programs have to agree on it, and only one type can be the agreement. The Kernel is the
//! only thing both are allowed to depend on: **EpochServices may not link the Engine**, because
//! linking it would put Quests, Chronicles, Knowledge and Trust inside a program this ADR says
//! must own none of them. A shape that lived in the Engine would be a shape the Bridge could not
//! see; a shape written twice would be two shapes.
//!
//! Zero I/O here, like everything else in the Kernel. These are the words, not the wire.
//!
//! ## The whole conversation
//!
//! ```text
//! remote → host   Hello    redeem a pairing code, and say what I am
//! host   → remote Welcome  keep this bearer; you are known now
//!
//! host   → remote Ask      here is a composed turn (bearer on every request)
//! remote → host   Told     here is what the model said
//!
//! host   → remote (What)   what do you have right now?
//! remote → host   Have     these models, this machine
//! ```
//!
//! Four shapes and no session. **The Bridge is stateless** (ADR-0029 §2): the Composer builds
//! the whole conversation every turn, so a tool result arrives as another message in the next
//! `Ask` rather than as a continuation of something the remote is holding. That is what makes
//! *unplug it and nothing is lost* true rather than aspirational.

use serde::{Deserialize, Serialize};

/// A remote machine introducing itself, code in hand.
///
/// **It reports its own address**, which is the whole reason the user never types an IP. A
/// machine knows where it is; asking a person to find out is asking them to do the computer's
/// job — and to do it again when DHCP changes the answer overnight.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Hello {
    /// The short code, read off the Host's screen.
    pub code: String,
    /// What this machine calls itself. A default the user may rename — never an identity.
    pub name: String,
    /// Where to reach it, as the machine itself knows it.
    pub address: String,
    /// The SHA-256 of the certificate this machine will answer with, lower-case hex.
    ///
    /// **The whole of the Host's certainty about who it is talking to afterwards.** There is no
    /// authority to ask on a home network, so what replaces one is this: the machine says which
    /// certificate is its own while the short code still stands, and every connection the Host
    /// makes from then on accepts that certificate and no other.
    ///
    /// A `String` rather than a type: the Kernel has no I/O and a fingerprint is sixty-four
    /// characters of hex. What it *means* lives in `epoch_wire::tls`, next to the thing that
    /// computes it.
    pub fingerprint: String,
    /// What it can do, measured on the machine that is offering it.
    pub have: Have,
}

/// The Host letting a machine in.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Welcome {
    /// The id the Host filed it under. Generated by the Host: a name the other end chooses is a
    /// name the other end can collide with.
    pub id: String,
    /// The long secret. Sent **once**, over the exchange the short code bought, and required on
    /// every request afterwards.
    pub secret: String,
}

/// A Host enrolling a machine that is showing a code — **the introduction, the other way round**.
///
/// ## Why there are two directions
///
/// [`Hello`] has the remote dial the Host, so the person never types an IP. That is the better
/// arrangement and it stays the default. It also requires that the remote can *open a connection
/// to* the Host, and on a real network that turned out not to be true: with the Mac on Wi-Fi and
/// the Host on Ethernet, every connection the Mac started was dropped — 445, 135, 3389 and
/// 11501 alike, with the firewall rule present and a listener confirmed up — while every
/// connection the Host started to the Mac succeeded. That is client isolation, it is the
/// router's decision, and it is not always somebody's to change.
///
/// So the *same* exchange runs backwards: the machine lending its models shows the code, and the
/// Host reaches out to it. Nothing else about the bond differs — same secret, same bearer, same
/// grants — because what changes is only who opens the socket.
///
/// ## What the code buys
///
/// It is checked **on the machine that showed it**, which is what keeps this safe in the
/// direction it now runs: anything on the network can reach that program, and without the code
/// none of it can enrol.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Enrol {
    /// The short code, read off the *remote's* screen this time.
    pub code: String,
    /// The long secret the Host will use afterwards. Minted by the Host, exactly as it is in the
    /// other direction — the side that will be presenting a bearer is the side that chooses it.
    pub secret: String,
    /// Where the Host is, so the machine can say who it belongs to and reach back if it ever
    /// needs to. Not a credential and never treated as one.
    pub host: String,
}

/// What the machine answers with, so the Host can file it.
///
/// **No id.** The Host generates that, here as in the other direction: a name the other end
/// chooses is a name the other end can collide with.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Enrolled {
    /// What this machine calls itself. A default the user may rename — never an identity.
    pub name: String,
    /// What it can do, measured on the machine that is offering it.
    pub have: Have,
}

/// What a remote machine has, measured there rather than guessed here.
///
/// Every number is optional for the same reason `Machine` states: a machine with no NVIDIA card
/// has no VRAM reading, and *unknown* is a different answer from *nothing fits*.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Have {
    /// Model names exactly as the local runtime lists them.
    #[serde(default)]
    pub models: Vec<String>,
    /// What the machine's own graphics card calls itself.
    #[serde(default)]
    pub gpu: Option<String>,
    #[serde(default)]
    pub vram_total: Option<u64>,
    #[serde(default)]
    pub vram_free: Option<u64>,
    #[serde(default)]
    pub ram_total: Option<u64>,
    /// **The graphics memory on that machine is its system memory.** True on Apple Silicon.
    ///
    /// On the wire because a Host describing a lent machine has to describe *that* machine: the
    /// numbers above are real either way, and calling them video memory on a unified machine
    /// implies a second pool to fall back into. There is none — what does not fit does not run
    /// slowly, it does not load.
    ///
    /// Defaults to `false`, so an older EpochServices that does not send it reads as *a machine
    /// with a card* — which is what every machine that could answer at all used to be.
    #[serde(default)]
    pub unified: bool,
    /// What EpochServices is, so a Host can say *update that machine* rather than fail oddly.
    #[serde(default)]
    pub version: String,
    /// Which programs on that machine can run a model, and what each of them is holding.
    ///
    /// ## Why `models` above was not enough
    ///
    /// It is one list, and it came from one program. A machine with Ollama *and* LM Studio has
    /// two shelves at two addresses holding different files, and a flat union could not say
    /// which was which — so a Host could offer a model that the runtime it was about to route
    /// to has never heard of. `Provider · Brain · Model` needs the middle term to exist on the
    /// wire before a surface can render it.
    ///
    /// Empty is an older EpochServices that was never asked. That is a different answer from
    /// *this machine runs nothing*, and the Host reads `models` under the machine's default
    /// runner when it sees one — which is exactly what it always did.
    #[serde(default)]
    pub runners: Vec<Runner>,
    /// Whether that machine can put a GGUF on disk, and who it is signed in as.
    ///
    /// **Measured there, like everything else here.** A machine lending a graphics card is a
    /// machine somebody may want to download a model onto, and whether it can is a property of
    /// *that* computer — `hf` being installed here says nothing about it. `None` is an older
    /// EpochServices that was never asked, which is not the same answer as *not installed*.
    #[serde(default)]
    pub hf: Option<HuggingFace>,
    /// Which programs on that machine can **make a picture**, and what each of them holds.
    ///
    /// ## Deliberately not in `runners`
    ///
    /// A diffusion server is not a Brain and must never appear in a list a character can be
    /// assigned to (ADR-0030): a character does not think in pictures, it asks for one. The two
    /// lists are drawn alike because they answer alike — installed, serving, holding — and kept
    /// apart because one of them answers turns and the other one does not.
    ///
    /// Empty is an older EpochServices that was never asked, which is a different answer from
    /// *this machine makes no pictures*. A Host that cannot tell those apart would offer to
    /// install ComfyUI onto a machine that has had it for a year.
    #[serde(default)]
    pub easels: Vec<Studio>,
}

/// One program on a machine that can turn a prompt into a picture.
///
/// The mirror of [`Runner`], and the same three facts for the same reason: *installed*,
/// *serving* and *holding something* have three different fixes, and a surface that collapsed
/// any two would send somebody to do the wrong one.
///
/// ## What rides along, and what does not
///
/// `install` and `first_run` come from the far machine because they are **that machine's**
/// answers — the command differs by platform, and a Host guessing `winget` for a MacBook would
/// be inventing a fix. `start` does not ride along: it is a path on a disk the Host cannot
/// reach, and a button that could not work is worse than a sentence saying to start it there.
///
/// Like [`HuggingFace`], a Kernel type rather than the measuring crate's: `epoch-models` depends
/// on nothing of Epoch's on purpose, so what crosses a Bridge cannot be its struct.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Studio {
    /// The stable id from the closed set — `comfyui` today.
    pub id: String,
    /// What a person calls it.
    pub name: String,
    #[serde(default)]
    pub installed: bool,
    #[serde(default)]
    pub serving: bool,
    /// Where it answered, as that machine sees it. Shown, never dialled: a loopback address
    /// means nothing here, and a Host that tried it would be reaching its own ComfyUI while
    /// believing it had reached somebody else's.
    #[serde(default)]
    pub endpoint: String,
    /// Checkpoints it reported. Empty while serving is honest and it is the interesting case:
    /// a running ComfyUI with no model is running perfectly and cannot make a picture.
    #[serde(default)]
    pub models: Vec<String>,
    /// How somebody installs it **there**, in that machine's own words.
    #[serde(default)]
    pub install: String,
    /// What it will ask that person the first time it opens.
    #[serde(default)]
    pub first_run: String,
}

/// One program on a machine that can run a model.
///
/// Called a **Brain** where a person can see it, and a `Runner` here: `Brain` is already the
/// Kernel's word for what a character's mind *is* (`mind::Brain`) and `Runtime` is already its
/// word for what progresses a Quest. Presentation vocabulary does not become domain
/// vocabulary — the same rule `Era`, `Party` and `History` follow.
///
/// **Identified, never addressed.** `id` is one of a closed set the far machine already knows
/// (`ollama`, `llama_cpp`, `lm_studio`) and it resolves there to a loopback port. An `Ask` that
/// could name a URL would be an `Ask` that could point that program at something else — which
/// is the one thing `here.rs` exists to prevent, and the reason a Bridge is safer than
/// `OLLAMA_HOST=0.0.0.0`.
///
/// `installed` and `serving` stay apart because they have different fixes, exactly as
/// [`HuggingFace`] keeps *installed* and *signed in* apart. A machine with LM Studio installed
/// and its server switched off is not a machine without LM Studio.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Runner {
    /// The stable id, from the closed set. This is what an [`Ask`] names.
    pub id: String,
    /// What a person calls it: `Ollama`, `llama.cpp`, `LM Studio`.
    pub name: String,
    /// Whether the program is on that machine at all.
    #[serde(default)]
    pub installed: bool,
    /// Whether its API answered just now. Measured by asking it, however it got there.
    #[serde(default)]
    pub serving: bool,
    /// What it **offers**, exactly as it lists it. Empty is honest: it is not running, or it
    /// has nothing.
    #[serde(default)]
    pub models: Vec<String>,
    /// What is **on the card right now**, which is a different question from what it offers.
    ///
    /// ## A shelf is not a card, across a network too
    ///
    /// The Host already draws this distinction for its own machine: a router listing five files
    /// on disk is not five models in memory, and the lamp over a conversation reads the card
    /// rather than the switch. None of that crossed a Bridge, so the KEEP control -- which is
    /// hidden when there is no reading -- was absent for every character whose brain lives on
    /// another computer. The *holding* worked the whole time; only the reading was missing.
    ///
    /// ## Why an `Option` and not an empty list
    ///
    /// `Some([])` is *asked, and nothing is loaded*. `None` is *an EpochServices old enough not
    /// to have been asked*, and those are the two answers a `Vec` cannot tell apart. Reading the
    /// second as the first would put a dark lamp over a model that is on the card, which is the
    /// same inversion this codebase has paid for in `uses_tools` and in `Shown`.
    #[serde(default)]
    pub resident: Option<Vec<String>>,
}

/// The Hugging Face CLI on some machine, as two separate facts.
///
/// Two facts because they have two fixes — one is solved by installing, the other by signing in
/// — and a surface that collapsed them would send somebody to do the wrong thing. The same shape
/// the agents' readiness takes, for the same reason (ADR-0027).
///
/// Deliberately a Kernel type rather than the measuring crate's: `epoch-models` depends on
/// nothing of Epoch's, on purpose, so what crosses a Bridge cannot be its struct.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HuggingFace {
    pub installed: bool,
    /// What it says it is. `None` when it is not there — never a guess.
    #[serde(default)]
    pub version: Option<String>,
    /// Where it was found, so "not installed" is a fact somebody can go and check.
    #[serde(default)]
    pub found_at: Option<String>,
    /// Who is signed in. `None` is *signed out or unreadable*, and an answer nobody can read is
    /// not an answer.
    #[serde(default)]
    pub user: Option<String>,
}

/// What one model says it can do.
///
/// ## Why this is in the Kernel now
///
/// It was the Engine's, and it was right there while the only models Epoch could ask about were
/// on this machine. A lent machine's models were then shown with no capabilities at all — the
/// crew editor drew the row for `gemma4:12b` on this computer and drew nothing for the same
/// model on the MacBook, which reads as *it cannot see* and is not what was measured. It was
/// never asked.
///
/// Same reasoning as [`HuggingFace`]: two programs have to agree on it, and only one type can be
/// the agreement.
///
/// The fields are the questions Epoch actually acts on. A backend that publishes more says more
/// than this type carries, deliberately: a field nothing reads is a field that goes stale.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Declared {
    /// It can be handed a picture.
    #[serde(default)]
    pub sees: bool,
    /// It can be handed audio. Nothing uses this yet — it is here because `gemma4:12b` says it
    /// and `gemma4:26b` does not, which is a fact worth showing a person choosing between them.
    #[serde(default)]
    pub hears: bool,
    /// It can be given tools and call them. **`None` is unasked, never *no*.**
    ///
    /// The only field here that changes what Epoch *does*, which is why it is the only one that
    /// had to grow a third state.
    ///
    /// It was a `bool`, on the reasoning that a model handed tools it cannot call does not fail
    /// — it ignores them, and the character answers as though they were never there. That is
    /// true, and the reasoning was written while only Ollama could answer, where every model
    /// declares `tools` and `false` really did mean *no*.
    ///
    /// Then llama.cpp and LM Studio gained a `declares()` that could describe a model's
    /// *modalities* and had nothing to say about tools — so they filled this in with `false`,
    /// the surface read `false` as a refusal, and **every character on those two backends was
    /// given no tools at all**. Measured 2026-08-24: `gemma4-12b` through LM Studio, asked for a
    /// picture, answered *"no tengo acceso a herramientas en este mundo"* — honestly, because
    /// Epoch had declared none. The same model through llama.cpp had made a real `draw_image`
    /// call an hour earlier, in a test that declared the tools itself.
    ///
    /// So the rule this crate already states for [`Shown`] applies here too, and for the same
    /// reason: silence is not an answer. Only a backend that genuinely says *no* may make a turn
    /// toolless.
    #[serde(default)]
    pub uses_tools: Option<bool>,
    /// It has a reasoning mode of its own.
    #[serde(default)]
    pub thinks: bool,
}

/// What a far machine says about one of its models.
///
/// Both facts arrive from one question, because asking them separately meant asking the network
/// twice for one answer — and over a Bridge that network is somebody's Wi-Fi.
///
/// Every field is optional and `None` means **unasked**, never *no*: a runtime with no way to
/// describe its models (llama.cpp and LM Studio publish an id and nothing else) answers nothing,
/// and reporting that model as blind would be an invented reading.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Shown {
    /// How much it can hold, as the model reports it.
    #[serde(default)]
    pub window: Option<u32>,
    /// What it says it can do.
    #[serde(default)]
    pub can: Option<Declared>,
}

/// One composed turn, going out.
///
/// Deliberately **not** a Quest, a Chronicle or a character. What crosses is what a `Provider`
/// takes: a model, messages and parameters. A machine that received more would have started
/// owning World state (ADR-0029 §1).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Ask {
    pub model: String,
    /// Which program on the far machine should run it — a [`Runner`] id, never an address.
    ///
    /// **`None` is what every Host said until this existed**, and it means *whatever that
    /// machine runs by default*, which is its Ollama. An id the far machine does not recognise
    /// is refused there rather than guessed at: routing a turn to something other than what was
    /// asked for is worse than saying so.
    #[serde(default)]
    pub runner: Option<String>,
    pub conversation: crate::Conversation,
    #[serde(default)]
    pub parameters: crate::Parameters,
    /// How long the far machine should keep this model resident once the turn is over.
    ///
    /// **The Host's decision, travelling.** It was not on this type, so a machine lending a
    /// graphics card kept every model its Ollama had loaded for its own default five minutes —
    /// with *Run several crew members at once* switched off on the Host. Measured on a MacBook:
    /// 8.3 GB still resident, and the toggle that was supposed to govern it only ever reached
    /// the Host's own runtime.
    ///
    /// `Some(0)` means let go now. `None` is an older Host that never said, and the far side
    /// leaves its runtime's own default alone rather than inventing an answer for it.
    #[serde(default)]
    pub keep_loaded_seconds: Option<u64>,
    /// What the character may reach for. Declared so the model can call them — and **the Host
    /// runs them**, never the Bridge (ADR-0029 §3).
    #[serde(default)]
    pub tools: Vec<crate::Descriptor>,
}

/// What came back.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Told {
    pub text: String,
    /// Anything it reached for. The Host judges these through Trust and runs them; the Bridge
    /// only reports that they were asked for.
    #[serde(default)]
    pub calls: Vec<crate::ToolCall>,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_hello_carries_its_own_address_so_nobody_types_one() {
        // The whole reason the user never sees an IP: a machine knows where it is, and asking a
        // person to find out is asking them to do the computer's job — twice, when DHCP changes
        // the answer.
        let hello = Hello {
            code: "K7M2QX".into(),
            name: "MacBook Pro".into(),
            address: "https://192.168.1.45:11500".into(),
            fingerprint: "9f".repeat(32),
            have: Have {
                models: vec!["qwen3:14b".into()],
                ram_total: Some(17_179_869_184),
                version: "0.1.0".into(),
                ..Have::default()
            },
        };
        let wire = serde_json::to_string(&hello).unwrap();
        assert!(wire.contains("192.168.1.45"));
        // And which certificate that address will answer with. Without it the Host would have
        // to decide who this machine is on some later connection, which is a decision made after
        // the code has expired and with nothing left to make it with.
        assert!(wire.contains(&"9f".repeat(32)));
        assert_eq!(serde_json::from_str::<Hello>(&wire).unwrap(), hello);
    }

    #[test]
    fn a_machine_with_no_card_reports_unknown_rather_than_zero() {
        // Same rule as `Machine`: "nobody could tell you" is not "nothing fits", and only one of
        // them was measured.
        let have: Have = serde_json::from_str(r#"{"models":["qwen3:14b"]}"#).unwrap();
        assert_eq!(have.vram_free, None);
        assert_eq!(have.gpu, None);
        assert_eq!(have.models.len(), 1);
    }

    #[test]
    fn an_older_machine_reports_no_runners_rather_than_none_at_all() {
        // Empty is *never asked*, not *runs nothing* — and the Host reads `models` under the
        // machine's default brain when it sees one, which is what it always did.
        let have: Have = serde_json::from_str(r#"{"models":["qwen3:14b"]}"#).unwrap();
        assert!(have.runners.is_empty());
        assert_eq!(have.models, vec!["qwen3:14b".to_owned()]);
    }

    #[test]
    fn a_runner_is_named_by_id_and_never_by_address() {
        // The whole security property of having a companion program: a request may say *which*
        // program, from a closed set the far machine already knows, and may not say *where*.
        let wire = serde_json::to_string(&Ask {
            model: "qwen3:14b".into(),
            runner: Some("lm_studio".into()),
            conversation: crate::Conversation::default(),
            parameters: crate::Parameters::default(),
            keep_loaded_seconds: None,
            tools: Vec::new(),
        })
        .unwrap();
        assert!(wire.contains("lm_studio"));
        for absent in ["http", "127.0.0.1", "localhost", "port"] {
            assert!(
                !wire.contains(absent),
                "an Ask may not carry an address: {wire}"
            );
        }
    }

    #[test]
    fn what_crosses_is_a_turn_and_never_a_quest() {
        // The security boundary, as a type. A machine that received a Quest would have started
        // owning World state — and the way to keep that true is for the shape to make it
        // unsayable rather than for a reviewer to notice.
        let wire = serde_json::to_string(&Ask {
            model: "qwen3:14b".into(),
            runner: None,
            conversation: crate::Conversation::default(),
            parameters: crate::Parameters::default(),
            keep_loaded_seconds: None,
            tools: Vec::new(),
        })
        .unwrap();

        for absent in ["quest", "chronicle", "trust", "world", "character"] {
            assert!(
                !wire.to_lowercase().contains(absent),
                "a turn must not carry the World: {wire}"
            );
        }
    }
}
